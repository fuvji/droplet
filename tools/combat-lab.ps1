[CmdletBinding()]
param(
    [string]$Csv = "combat.csv",
    [string]$OutFile = (Join-Path $env:LOCALAPPDATA "Hydrogen\combat.profile"),
    [int]$MinSamples = 6
)

# Offline combat timing lab. It never reads video or network data; it consumes
# timestamped hit annotations you have already labelled from footage you may use.
$ErrorActionPreference = "Stop"
Set-StrictMode -Version 2.0

if (-not (Test-Path -LiteralPath $Csv)) {
    throw "CSV not found: $Csv"
}
if ($MinSamples -lt 1) {
    throw "MinSamples must be at least 1"
}

$rows = @(Import-Csv -LiteralPath $Csv)
if ($rows.Count -eq 0) {
    throw "CSV is empty: $Csv"
}
$headers = @($rows[0].PSObject.Properties.Name)
foreach ($required in @("clip", "module", "time_ms", "hit")) {
    if ($headers -notcontains $required) {
        throw "Missing required CSV column: $required"
    }
}

# Canonical module names. vC is the config key; wtap is the runtime slot.
$moduleMap = @{
    "vD" = "vD"; "v1" = "v1"; "v2" = "v2"; "v3" = "v3"; "v4" = "v4"
    "v5" = "v5"; "v6" = "v6"; "v7" = "v7"; "v8" = "v8"; "vA" = "vA"
    "vW" = "vW"; "vC" = "wtap"; "wtap" = "wtap"
}

$events = New-Object System.Collections.Generic.List[object]
foreach ($row in $rows) {
    $hit = ([string]$row.hit).Trim().ToLowerInvariant()
    if (@("1", "true", "yes", "hit") -notcontains $hit) {
        continue
    }
    $module = ([string]$row.module).Trim()
    if (-not $moduleMap.ContainsKey($module)) {
        continue
    }
    $time = 0.0
    $text = ([string]$row.time_ms).Trim()
    if (-not [double]::TryParse(
        $text,
        [Globalization.NumberStyles]::Float,
        [Globalization.CultureInfo]::InvariantCulture,
        [ref]$time
    )) {
        continue
    }
    $clip = ([string]$row.clip).Trim()
    if ([string]::IsNullOrWhiteSpace($clip)) {
        $clip = "clip"
    }
    $events.Add([pscustomobject]@{
        Clip = $clip
        Module = $moduleMap[$module]
        TimeMs = $time
    })
}

if ($events.Count -eq 0) {
    throw "No usable confirmed-hit rows found"
}

$entries = New-Object System.Collections.Generic.List[string]
foreach ($moduleGroup in ($events | Group-Object Module)) {
    $intervals = New-Object System.Collections.Generic.List[double]
    foreach ($clipGroup in ($moduleGroup.Group | Group-Object Clip)) {
        $times = @($clipGroup.Group | ForEach-Object { [double]$_.TimeMs } | Sort-Object)
        for ($i = 1; $i -lt $times.Count; $i++) {
            $delta = $times[$i] - $times[$i - 1]
            if ($delta -gt 0.0 -and $delta -le 2000.0) {
                $intervals.Add($delta)
            }
        }
    }
    if ($intervals.Count -lt $MinSamples) {
        continue
    }

    $sorted = @($intervals | Sort-Object)
    $mid = [int][Math]::Floor($sorted.Count / 2)
    if ($sorted.Count % 2 -eq 1) {
        $median = [double]$sorted[$mid]
    } else {
        $median = ([double]$sorted[$mid - 1] + [double]$sorted[$mid]) / 2.0
    }
    $value = [int][Math]::Round($median, [MidpointRounding]::AwayFromZero)
    $value = [Math]::Min(500, [Math]::Max(35, $value))
    $entries.Add(("{0}={1}" -f $moduleGroup.Name, $value))
}

if ($entries.Count -eq 0) {
    throw "No module had $MinSamples usable confirmed-hit intervals"
}

$directory = Split-Path -Parent $OutFile
if (-not [string]::IsNullOrWhiteSpace($directory)) {
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
}
$lines = @(
    "# Hydrogen combat profile v1",
    "# Generated by tools/combat-lab.ps1; runtime clamps every value.",
    ""
) + @($entries)
[System.IO.File]::WriteAllLines(
    $OutFile,
    [string[]]$lines,
    (New-Object System.Text.UTF8Encoding($false))
)

Write-Host ("Wrote {0} module profile(s) to {1}" -f $entries.Count, $OutFile)
$entries | ForEach-Object { Write-Host ("  {0}" -f $_) }
